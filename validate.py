"""Sanity checks: run `python validate.py` (all must print OK)."""
import numpy as np
from qiskit.quantum_info import Statevector

from bloodq.config import Params
from bloodq.qubo import Subproblem, build_qubo, all_bits, energies, feasible_mask, to_ising, count_qubits
from bloodq.qaoa import QAOA
from bloodq.circuits import qaoa_circuit, grover_circuit
from bloodq.grover import grover_probs, optimal_iterations
from bloodq.data_gen import abo_rh_compatible


def toy_sub():
    recips = [dict(rid="P1", D=2, w=5, p=5), dict(rid="P2", D=2, w=3, p=3)]
    sources = [dict(key=1, cap=2, tier=1), dict(key=2, cap=3, tier=2)]
    pairs = {(0, 0): dict(w=5, time=60, exact=True), (0, 1): dict(w=3, time=60, exact=True),
             (1, 0): dict(w=5, time=240, exact=True), (1, 1): dict(w=3, time=240, exact=True)}
    return Subproblem(recips, sources, pairs)


def main():
    # 1. slide 17-19 worked examples
    assert -5 * 2 == -10 and -3 * 2 == -6, "slide 17"
    # NOTE slide 18 prints 1 and 4 for "lambda*c*y" with y=2; the correct values are 2 and 8
    # (1 and 4 are the per-unit costs lambda*c). The code uses the correct formula.
    assert abs(0.1 * 10 * 2 - 2) < 1e-12 and abs(0.1 * 40 * 2 - 8) < 1e-12, "slide 18 (corrected)"
    assert 10 * 5 * 2 == 100 and 10 * 3 * 2 == 60, "slide 19"
    # slide 20 encoding: 5 units -> b=(1,0,1)
    assert 1 * 1 + 2 * 0 + 4 * 1 == 5
    print("OK  slide worked examples")

    # 2. compatibility table
    assert abo_rh_compatible("O-", "AB+") and not abo_rh_compatible("AB+", "O-") and not abo_rh_compatible("A+", "A-")
    assert abo_rh_compatible("B-", "AB-") and not abo_rh_compatible("A-", "B-")
    print("OK  ABO/Rh compatibility")

    # 3. QUBO: Ising mapping reproduces QUBO energies; global optimum is feasible and equals brute force intuition
    sub = toy_sub()
    q = build_qubo(sub, lam=0.1, mu=1.0, penalty_scale=1.2)
    X = all_bits(q.n)
    E = energies(q, X)
    h, J, off = to_ising(q)
    Z = 1 - 2 * X.astype(float)
    E_ising = Z @ h + sum(v * Z[:, i] * Z[:, j] for (i, j), v in J.items()) + off
    assert np.abs(E - E_ising).max() < 1e-8, "Ising mapping"
    F = feasible_mask(q, X)
    assert F[np.argmin(E)], "penalties too small: QUBO optimum infeasible"
    print(f"OK  QUBO ({q.n} qubits): Ising mapping exact, optimum feasible, min E = {E.min():.3f}")

    # 4. QAOA probability distribution is generated by the Qiskit circuit/statevector
    p = 2
    qa = QAOA(E, q.n, p, Q=q.Q)
    params = np.array([0.4, 0.7, 0.3, 0.2])
    pr_qk = qa.probs(params)
    qc = qaoa_circuit(h, J, params[:p], params[p:], scale=qa.scale)
    pr_check = Statevector.from_instruction(qc).probabilities()
    assert np.abs(pr_qk - pr_check).max() < 1e-9
    print("OK  QAOA probabilities generated by Qiskit Statevector")

    # 5. Grover probabilities are generated by a Qiskit circuit/statevector
    n, marked = 5, [7, 19]
    r = optimal_iterations(1 << n, len(marked))
    mask = np.zeros(1 << n, bool)
    mask[marked] = True
    p_qk = grover_probs(n, mask, r)
    p_check = Statevector.from_instruction(grover_circuit(n, marked, r)).probabilities()
    assert np.abs(p_qk - p_check).max() < 1e-9
    print(f"OK  Grover Qiskit circuit (n={n}, M=2, r={r}, P(success)={p_qk[mask].sum():.4f})")

    # 6. Grover single marked: success prob high, r ~ pi/4 sqrt(N)
    for n in (4, 8, 10):
        N = 1 << n
        mask = np.zeros(N, bool)
        mask[3] = True
        r = optimal_iterations(N, 1)
        assert grover_probs(n, mask, r)[3] > 0.95
    print("OK  Grover success probability > 0.95 for M=1, n=4,8,10")
    print("ALL CHECKS PASSED")


if __name__ == "__main__":
    main()
